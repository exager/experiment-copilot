"""Report Agent node.

Computes the business impact estimate deterministically, then asks the LLM
to write the executive summary and next steps around it. The
recommendation category and business impact number are never generated by
the LLM.
"""

from __future__ import annotations

from pathlib import Path

from app.agents import llm
from app.agents.llm import with_retry
from app.schemas.agent_outputs import ReportNarrative

_PROMPT = (Path(__file__).resolve().parent.parent / "prompts" / "report.md").read_text()

NEXT_ACTIONS: dict[str, list[str]] = {
    "scale": ["Rollout to 100%", "Continue monitoring performance", "Keep guardrail metrics active"],
    "continue": ["Let the experiment run longer to reach significance", "Keep monitoring guardrail metrics"],
    "stop": ["Halt the rollout", "Investigate why the variant underperformed"],
    "rollback": ["Revert to the control experience immediately", "Investigate the guardrail regression"],
}


def estimate_business_impact(statistics: dict, metrics: dict | None = None) -> str:
    """Deterministic business impact estimate.

    Formats a plain string like "+8% Monthly Revenue" from the computed
    lift, or a revenue-delta figure when revenue numbers are available.
    """
    metrics = metrics or {}
    revenue_control = metrics.get("revenue_control")
    revenue_variant = metrics.get("revenue_variant")
    if revenue_control and revenue_variant:
        delta_pct = (revenue_variant - revenue_control) / revenue_control * 100
        return f"{delta_pct:+.1f}% estimated revenue impact"

    lift = statistics.get("conversion_lift") or 0.0
    return f"{lift * 100:+.1f}% conversion lift"


@with_retry
def node(state: dict) -> dict:
    statistics = state.get("statistics") or {}
    metrics = state.get("metrics") or {}
    recommendation = state.get("recommendation") or {}
    category = recommendation.get("recommendation", "continue")

    business_impact = estimate_business_impact(statistics, metrics)

    prompt = _PROMPT.format(
        business_goal=state.get("business_goal", ""),
        hypothesis=(state.get("hypothesis") or {}).get("hypothesis", ""),
        configuration=state.get("configuration") or {},
        statistics=statistics,
        recommendation=category,
        business_impact=business_impact,
    )
    model = llm.get_llm().with_structured_output(ReportNarrative)
    result: ReportNarrative = model.invoke(prompt)

    report = {
        "summary": result.summary,
        "recommendation": category,
        "business_impact": business_impact,
        "next_steps": result.next_steps or NEXT_ACTIONS.get(category, []),
        "details": {
            "business_goal": state.get("business_goal"),
            "hypothesis": state.get("hypothesis"),
            "configuration": state.get("configuration"),
            "statistics": statistics,
        },
    }
    return {"report": report}
